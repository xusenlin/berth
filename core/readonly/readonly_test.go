func TestSQLiteReadOnly(t *testing.T) {
	out, err := Check(`sqlite3 ./x.db 'select 1' | head`)
	if err != nil || out != "sqlite3 -readonly -safe ./x.db 'select 1' | head\n" {
		t.Errorf("got %q %v", out, err)
	}
}

