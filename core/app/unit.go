package app

import (
	"maps"
	"slices"
	"strconv"
	"strings"

	"github.com/xusenlin/berth/core/server"
)

// ExpandArgs replaces {{port}} and {{shared}} in the app's arguments.
func ExpandArgs(a App, env server.Env) string {
	port := ""
	if a.Port > 0 {
		port = strconv.Itoa(a.Port)
	}
	return strings.NewReplacer(
		"{{port}}", port,
		"{{shared}}", PathsOf(env, a.Name).Shared,
	).Replace(a.Args)
}

// RenderUnit returns the systemd unit file of an app.
func RenderUnit(a App, env server.Env) string {
	p := PathsOf(env, a.Name)
	target := "default.target"
	if env.Mode == server.ModeRoot {
		target = "multi-user.target"
	}
	exec := unitQuote(p.Current + "/" + a.Entry)
	if args := ExpandArgs(a, env); args != "" {
		exec += " " + escapePercent(args)
	}
	var b strings.Builder
	w := func(s ...string) {
		for _, x := range s {
			b.WriteString(x)
		}
		b.WriteByte('\n')
	}
	w("# Generated by Berth. Edit the app in Berth rather than this file.")
	w("[Unit]")
	w("Description=senlin app: ", a.Name)
	w("After=network-online.target")
	w("Wants=network-online.target")
	w()
	w("[Service]")
	w("WorkingDirectory=", unitQuote(p.Current))
	w("ExecStart=", exec)
	w("EnvironmentFile=-", unitQuote(p.EnvFile))
	w("Restart=", string(a.Restart))
	w("RestartSec=3")
	w()
	w("[Install]")
	w("WantedBy=", target)
	return b.String()
}

// unitQuote quotes a path for a unit file when it needs it.
func unitQuote(s string) string {
	s = escapePercent(s)
	if strings.ContainsAny(s, " \t\"'\\") {
		return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
	}
	return s
}

// escapePercent keeps systemd from reading % as a specifier.
func escapePercent(s string) string { return strings.ReplaceAll(s, "%", "%%") }

// RenderEnvFile returns the EnvironmentFile of an app's variables, with
// PORT set when the app has a port and the variables do not set it.
func RenderEnvFile(a App) string {
	vars := maps.Clone(a.Env)
	if vars == nil {
		vars = map[string]string{}
	}
	if _, ok := vars["PORT"]; !ok && a.Port > 0 {
		vars["PORT"] = strconv.Itoa(a.Port)
	}
	var b strings.Builder
	b.WriteString("# Generated by Berth from app.json.\n")
	for _, k := range slices.Sorted(maps.Keys(vars)) {
		b.WriteString(k)
		b.WriteString(`="`)
		b.WriteString(strings.NewReplacer(`\`, `\\`, `"`, `\"`, "$", `\$`, "`", "\\`").Replace(vars[k]))
		b.WriteString("\"\n")
	}
	return b.String()
}
