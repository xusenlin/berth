var rootEnv = server.Env{User: "root", UID: 0, Home: "/root", Mode: server.ModeRoot}
var userEnv = server.Env{User: "deploy", UID: 1000, Home: "/home/deploy", Mode: server.ModeUser}

func TestNormalize(t *testing.T) {
	a := App{Name: "myapp", Entry: "myapp", Shared: []string{"/pb_data/", "pb_data", " "}}
	if err := a.Normalize(); err != nil {
		t.Fatal(err)
	}
	if a.Restart != RestartOnFailure || a.Health.Type != HealthProcess || a.KeepReleases != 5 || a.Health.Timeout != 10 {
		t.Errorf("defaults: %+v", a)
	}
	if len(a.Shared) != 1 || a.Shared[0] != "pb_data" {
		t.Errorf("shared = %q", a.Shared)
	}
	bad := []App{
		{Name: "My App", Entry: "x"},
		{Name: "a", Entry: ""},
		{Name: "a", Entry: "../x"},
		{Name: "a", Entry: "/bin/x"},
		{Name: "a", Entry: "x", Shared: []string{"../etc"}},
		{Name: "a", Entry: "x", Health: Health{Type: HealthHTTP}},
		{Name: "a", Entry: "x", Env: map[string]string{"1X": "v"}},
		{Name: "a", Entry: "x", Args: "a\nb"},
		{Name: "a", Entry: "x", Restart: "sometimes"},
	}
	for i, b := range bad {
		if err := b.Normalize(); err == nil {
			t.Errorf("case %d: expected error for %+v", i, b)
		}
	}
}

func TestRenderUnit(t *testing.T) {
	a := App{Name: "pb", Entry: "pocketbase", Args: "serve --http=0.0.0.0:{{port}} --dir={{shared}}/pb_data --x=50%", Port: 18001, Restart: RestartOnFailure}
	got := RenderUnit(a, rootEnv)
	for _, want := range []string{
		"WorkingDirectory=/root/senlinApps/pb/current\n",
		"ExecStart=/root/senlinApps/pb/current/pocketbase serve --http=0.0.0.0:18001 --dir=/root/senlinApps/pb/shared/pb_data --x=50%%\n",
		"EnvironmentFile=-/root/senlinApps/pb/shared/.env\n",
		"Restart=on-failure\n",
		"WantedBy=multi-user.target\n",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("unit lacks %q:\n%s", want, got)
		}
	}
	if u := RenderUnit(a, userEnv); !strings.Contains(u, "WantedBy=default.target") || !strings.Contains(u, "/home/deploy/senlinApps/pb/current") {
		t.Errorf("user unit:\n%s", u)
	}
}

func TestRenderEnvFile(t *testing.T) {
	got := RenderEnvFile(App{Port: 8080, Env: map[string]string{"B": `a "q" $HOME \`, "A": "1"}})
	want := "# Generated by Berth from app.json.\nA=\"1\"\nB=\"a \\\"q\\\" \\$HOME \\\\\"\nPORT=\"8080\"\n"
	if got != want {
		t.Errorf("got\n%s\nwant\n%s", got, want)
	}
	if got := RenderEnvFile(App{Port: 8080, Env: map[string]string{"PORT": "9"}}); !strings.Contains(got, `PORT="9"`) || strings.Contains(got, "8080") {
		t.Errorf("PORT override: %s", got)
	}
}

func TestParseList(t *testing.T) {
	out := `@@app myapp
{"name":"myapp","entry":"myapp","port":18001,"current":"20261009-151800"}

@@current
releases/20261009-151800
@@show
LoadState=loaded
ActiveState=active
SubState=running
MainPID=4242
ActiveEnterTimestampMonotonic=1000000000
MemoryCurrent=50331648
CPUUsageNSec=1200000000
UnitFileState=enabled
NRestarts=2
@@app broken
{not json

@@current
@@show
LoadState=not-found
ActiveState=inactive
MemoryCurrent=[not set]
@@uptime
1100.00 2000.00
`
	infos := parseList(out)
	if len(infos) != 2 {
		t.Fatalf("got %d apps", len(infos))
	}
	a := infos[0]
	if a.App.Port != 18001 || a.Current != "20261009-151800" {
		t.Errorf("app: %+v", a)
	}
	s := a.Status
	if !s.Installed || !s.Running() || s.PID != 4242 || !s.Enabled || s.Restarts != 2 || s.Memory != 48<<20 || s.Uptime != 100 {
		t.Errorf("status: %+v", s)
	}
	b := infos[1]
	if b.Error == "" || b.App.Name != "broken" || b.Status.Installed || b.Status.Memory != -1 {
		t.Errorf("broken: %+v", b)
	}
}

